//! Reading `Cargo.lock`: the exact crate versions a project builds with.

/// One registry package named in a lockfile.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Locked {
    pub name: String,
    pub version: String,
    /// `registry+<url>` or `sparse+<url>`.
    pub source: String,
    /// SHA-256 of the `.crate`, hex. Old (version 1) lockfiles keep it elsewhere.
    pub checksum: Option<String>,
}

/// The value of a `key = "value"` line, if the line is one.
fn string_value<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let rest = line.strip_prefix(key)?.trim_start().strip_prefix('=')?.trim();
    let inner = rest.strip_prefix('"')?.strip_suffix('"')?;
    (!inner.contains(['"', '\\'])).then_some(inner)
}

/// Registry packages of a lockfile. Path and git dependencies (no `source`,
/// or `git+...`) are not in any registry and are left out.
pub fn parse_lockfile(text: &str) -> Result<Vec<Locked>, String> {
    #[derive(Default)]
    struct Partial {
        name: Option<String>,
        version: Option<String>,
        source: Option<String>,
        checksum: Option<String>,
    }
    fn finish(cur: Option<Partial>, out: &mut Vec<Locked>) -> Result<(), String> {
        let Some(p) = cur else { return Ok(()) };
        let (Some(name), Some(version)) = (p.name, p.version) else {
            return Err("a [[package]] entry lacks a name or version".into());
        };
        if let Some(source) = p.source.filter(|s| s.starts_with("registry+") || s.starts_with("sparse+")) {
            out.push(Locked { name, version, source, checksum: p.checksum });
        }
        Ok(())
    }
    let mut out = Vec::new();
    let mut current: Option<Partial> = None;
    for raw in text.lines() {
        let line = raw.trim();
        if line.starts_with('[') {
            finish(current.take(), &mut out)?;
            if line == "[[package]]" {
                current = Some(Partial::default());
            }
            continue;
        }
        let Some(cur) = current.as_mut() else { continue };
        let field = [("name", &mut cur.name), ("version", &mut cur.version), ("source", &mut cur.source), ("checksum", &mut cur.checksum)];
        for (key, slot) in field {
            if let Some(v) = string_value(line, key) {
                *slot = Some(v.to_string());
                break;
            }
        }
    }
    finish(current.take(), &mut out)?;
    if out.is_empty() && !text.contains("[[package]]") {
        return Err("not a Cargo.lock (no [[package]] entries)".into());
    }
    Ok(out)
}

#[cfg(test)]
mod unit {
    use super::*;

    #[test]
    fn registry_packages_are_read_and_local_ones_skipped() {
        let text = r#"
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde",
 "anyhow",
]

[[package]]
name = "serde"
version = "1.0.210"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "c8e3592472072e6e22e0a54d5904d9febf8508f65fb8552499a1abc7d1078c3a"

[[package]]
name = "anyhow"
version = "1.0.89"
source = "sparse+https://index.crates.io/"
checksum = "86fdf8605db99b54d3cd748a44c6d04df638eb5dafb219b135d0149bd0db01f6"

[[package]]
name = "forked"
version = "0.3.0"
source = "git+https://example.com/forked#abc"
"#;
        let got = parse_lockfile(text).unwrap();
        assert_eq!(got.len(), 2);
        assert_eq!(got[0].name, "serde");
        assert_eq!(got[0].version, "1.0.210");
        assert_eq!(got[1].source, "sparse+https://index.crates.io/");
        assert!(got[1].checksum.as_deref().unwrap().starts_with("86fd"));
        assert!(parse_lockfile("hello").is_err());
    }
}
